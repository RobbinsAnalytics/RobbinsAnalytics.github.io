#!/usr/bin/env python3
"""Draw the Build by Build matrix for the homepage feature card.

    python tools/build_bbb_grid.py        (Quarto runs it as a pre-render script)

Reads the committed snapshot data/build-by-build.json (ten builds, fourteen
test surfaces; provenance in data/build-by-build.provenance.json) and writes
_generated/bbb-grid.html, which index.qmd includes beside the feature card's
text. Nothing is fetched: candidate and deploy draw the same bytes, and a
refreeze of the matrix is a pull request that replaces the snapshot.

The grid is the real matrix, not a decoration (Aaron's note 12, 2026-10-15):
rows are the builds in first-commit order, columns are the surfaces in the
band order the Build by Build repository uses, and a cell is present or
absent. One fill for present and one for absent, with no intensity step,
because the underlying state is binary and a brighter cell would read as a
larger value. The visible caption's counts are computed here, never typed.
"""

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "data" / "build-by-build.json"
PROVENANCE = ROOT / "data" / "build-by-build.provenance.json"
OUT = ROOT / "_generated" / "bbb-grid.html"
LIVE = "https://www.robbinsanalytics.com/cascadia-build-by-build/"

# Column order, copied from BANDS in src/inventory.py of
# RobbinsAnalytics/cascadia-build-by-build at the freeze commit. The snapshot
# stores the surfaces alphabetically, so the order has to live here.
BANDS = [
    ("Data", ["one_command_rebuild", "frozen_source", "source_register"]),
    ("Numbers", ["row_count_validation", "validation_report", "tests_as_code",
                 "independent_rederivation", "golden_fixture", "negative_controls"]),
    ("Presentation", ["chart_review", "reading_panel", "metric_register"]),
    ("Operation", ["scheduled_run_with_health", "reconciliation_published"]),
]
SURFACES = [s for _, band in BANDS for s in band]


def main():
    builds = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    prov = json.loads(PROVENANCE.read_text(encoding="utf-8"))
    builds = sorted(builds, key=lambda b: b["first_commit"])
    keys = set(SURFACES)
    for b in builds:
        if set(b["surfaces"]) != keys:
            sys.exit("build_bbb_grid: %s has surfaces %s, expected the fourteen in BANDS"
                     % (b["name"], sorted(b["surfaces"])))

    rows, cols = len(builds), len(SURFACES)
    present = sum(1 for b in builds for s in SURFACES if b["surfaces"][s])
    frozen = prov["frozen_on"]

    bands = "".join(
        '<span class="fx-matrix__band" style="--span:%d">%s</span>' % (len(band), html.escape(name))
        for name, band in BANDS)
    cells = []
    for b in builds:
        for s in SURFACES:
            on = bool(b["surfaces"][s])
            cells.append('<span class="fx-matrix__cell%s" data-build="%s" data-surface="%s"></span>'
                         % (" is-on" if on else "", html.escape(b["key"]), s))
    desc = ("The Build by Build matrix: %d builds by %d test surfaces, %d of %d cells present. "
            "Each row is one Cascadia build in first-commit order, from %s to %s. Each column is one "
            "test surface, in four bands: Data (%d), Numbers (%d), Presentation (%d) and Operation (%d). "
            "A filled cell means the build carried that test surface when it shipped. The inventory was "
            "frozen on %s. The full matrix, with every filled cell linked to the file it names, is the "
            "Build by Build page." % (
                rows, cols, present, rows * cols, builds[0]["name"], builds[-1]["name"],
                len(BANDS[0][1]), len(BANDS[1][1]), len(BANDS[2][1]), len(BANDS[3][1]), frozen))

    out = f'''<!-- Generated by tools/build_bbb_grid.py from data/build-by-build.json; do not edit. -->
<div class="fx-matrix" data-rows="{rows}" data-cols="{cols}" data-present="{present}">
  <div class="fx-matrix__bands" aria-hidden="true">{bands}</div>
  <div class="fx-matrix__grid" role="img" aria-labelledby="fx-matrix-caption" aria-describedby="fx-matrix-desc" style="--cols:{cols}">{"".join(cells)}</div>
  <p class="fx-matrix__caption" id="fx-matrix-caption">{rows} builds &#215; {cols} test surfaces &#183; {present} of {rows * cols} present &#183; <span style="white-space:nowrap">frozen {frozen}</span></p>
  <p class="visually-hidden" id="fx-matrix-desc">{html.escape(desc)}</p>
</div>
'''
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print("  wrote %s (%d x %d, %d present, frozen %s)"
          % (OUT.relative_to(ROOT).as_posix(), rows, cols, present, frozen))


if __name__ == "__main__":
    main()
