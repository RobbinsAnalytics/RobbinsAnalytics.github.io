#!/usr/bin/env python3
"""Write the site footer from the portfolio inventory.

    python tools/build_footer.py          (Quarto runs it as a pre-render script)

Writes _generated/footer.html, which _quarto.yml includes after the body of
every page (format.html.include-after-body). Quarto's own page-footer is not
used: it has three text slots and Felix's footer (felix-design-system.md
§6.11) is four columns plus a legal strip, and its "Featured builds" column
is read from data/portfolio.yml so that it cannot drift from the homepage
and the index, which are rendered from the same file.

_generated/ is gitignored. The file is rebuilt on every render, so a clean
checkout renders without it present. Needs PyYAML, which both workflows
install before `quarto render`.
"""

import html
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "data" / "portfolio.yml"
OUT = ROOT / "_generated" / "footer.html"

SITE_DESCRIPTION = ("AI analytics architecture portfolio, Aaron Robbins. "
                    "Governed analytics, built with AI and proven by tests.")

EXPLORE = [
    ("Home", "/"),
    ("About", "/about.html"),
    ("About Cascadia", "/cascadia/"),
    ("All case studies", "/case-studies.html"),
]

# Bootstrap Icons (MIT), inlined so the footer does not depend on Quarto
# shipping the icon font once page-footer is gone.
ICON_LINKEDIN = ('<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 16 16" '
                 'fill="currentColor" aria-hidden="true" focusable="false"><path d="M0 1.146C0 .513.526 0 1.175 0h13.65C15.474 0 16 .513 16 1.146v13.708c0 .633-.526 1.146-1.175 1.146H1.175C.526 16 0 15.487 0 14.854zm4.943 12.248V6.169H2.542v7.225zm-1.2-8.212c.837 0 1.358-.554 1.358-1.248-.015-.709-.52-1.248-1.342-1.248S2.4 3.226 2.4 3.934c0 .694.521 1.248 1.327 1.248zm4.908 8.212V9.359c0-.216.016-.432.08-.586.173-.431.568-.878 1.232-.878.869 0 1.216.662 1.216 1.634v3.865h2.401V9.25c0-2.22-1.184-3.252-2.764-3.252-1.274 0-1.845.7-2.165 1.193v.025h-.016l.016-.025V6.169h-2.4c.03.678 0 7.225 0 7.225z"/></svg>')
ICON_GITHUB = ('<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 16 16" '
               'fill="currentColor" aria-hidden="true" focusable="false"><path d="M8 0C3.58 0 0 3.58 0 8c0 3.54 2.29 6.53 5.47 7.59.4.07.55-.17.55-.38 0-.19-.01-.82-.01-1.49-2.01.37-2.53-.49-2.69-.94-.09-.23-.48-.94-.82-1.13-.28-.15-.68-.52-.01-.53.63-.01 1.08.58 1.23.82.72 1.21 1.87.87 2.33.66.07-.52.28-.87.51-1.07-1.78-.2-3.64-.89-3.64-3.95 0-.87.31-1.59.82-2.15-.08-.2-.36-1.02.08-2.12 0 0 .67-.21 2.2.82.64-.18 1.32-.27 2-.27s1.36.09 2 .27c1.53-1.04 2.2-.82 2.2-.82.44 1.1.16 1.92.08 2.12.51.56.82 1.27.82 2.15 0 3.07-1.87 3.75-3.65 3.95.29.25.54.73.54 1.48 0 1.07-.01 1.93-.01 2.2 0 .21.15.46.55.38A8.01 8.01 0 0 0 16 8c0-4.42-3.58-8-8-8"/></svg>')


def main():
    items = yaml.safe_load(INVENTORY.read_text(encoding="utf-8"))
    items = sorted(items, key=lambda i: i["order"])
    feature = [i for i in items if i["slug"] == "build-by-build"]
    featured = [i for i in items if i.get("featured") is True]
    builds = feature + featured
    if not feature or len(featured) != 3:
        sys.exit("build_footer: expected Build by Build plus three featured entries, "
                 "found %d and %d" % (len(feature), len(featured)))

    def title(i):
        fam = i.get("family") or ""
        return (fam + " " if fam else "") + i["title"]

    def links(rows):
        return "".join('<li><a href="%s">%s</a></li>' % (html.escape(h), html.escape(t)) for t, h in rows)

    out = f'''<!-- Generated by tools/build_footer.py from data/portfolio.yml; do not edit. -->
<footer class="fx-footer" id="fx-footer">
  <div class="fx-footer__inner">
    <div class="fx-footer__brand">
      <a class="fx-footer__wordmark" href="/" aria-label="Robbins Analytics, home">
        <img src="/assets/brand/robbins-mark-reversed.svg" alt="" width="52" height="44">
        <span class="fx-wordmark">Robbins <em>Analytics</em><span class="fx-wm-stop">.</span></span>
      </a>
      <p class="fx-footer__blurb">{html.escape(SITE_DESCRIPTION)}</p>
    </div>
    <nav class="fx-footer__col" aria-label="Explore">
      <p class="fx-footer__head">Explore</p>
      <ul>{links(EXPLORE)}</ul>
    </nav>
    <nav class="fx-footer__col" aria-label="Featured builds">
      <p class="fx-footer__head">Featured builds</p>
      <ul>{links([(title(i), i["href"]) for i in builds])}</ul>
    </nav>
    <div class="fx-footer__col">
      <p class="fx-footer__head">Connect</p>
      <ul class="fx-footer__social">
        <li><a href="https://www.linkedin.com/in/aaron-robbins-6b25a2136/" aria-label="LinkedIn — Aaron Robbins">{ICON_LINKEDIN}</a></li>
        <li><a href="https://github.com/RobbinsAnalytics" aria-label="GitHub — Robbins Analytics">{ICON_GITHUB}</a></li>
      </ul>
      <a class="fx-footer__top" href="#quarto-header">Back to top <span class="fx-footer__top-disc" aria-hidden="true">&#8593;</span></a>
    </div>
  </div>
  <div class="fx-footer__legal">
    <span>&#169; 2026 Aaron Robbins</span>
    <span class="fx-footer__tag">Trust what you can test</span>
  </div>
</footer>
'''
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print("  wrote %s (%d featured builds)" % (OUT.relative_to(ROOT).as_posix(), len(builds)))


if __name__ == "__main__":
    main()
