#!/usr/bin/env python3
"""Write the homepage stat strip from data/stats.json.

    python tools/build_stats.py           (Quarto runs it as a pre-render script)

Writes _generated/stats.html, which index.qmd includes. One source for the
five tiles: the same file tools/check_references.py checks, tile by tile,
against the pages and the snapshot they quote. The two portfolio tiles are
recomputed from data/build-by-build.json here as well, so the number on the
page is the snapshot's and never a typed copy of it.
"""

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATS = ROOT / "data" / "stats.json"
OUT = ROOT / "_generated" / "stats.html"


def computed(kind, snapshot):
    builds = json.loads((ROOT / snapshot).read_text(encoding="utf-8"))
    if kind == "rows":
        return str(len(builds))
    if kind == "surfaces":
        keys = {k for b in builds for k in b["surfaces"]}
        return str(len(keys))
    sys.exit("build_stats: unknown compute %r" % kind)


def main():
    data = json.loads(STATS.read_text(encoding="utf-8"))
    tiles = data["tiles"]
    if len(tiles) != 5:
        sys.exit("build_stats: expected five tiles, found %d" % len(tiles))
    cells = []
    for n, t in enumerate(tiles, 1):
        value = computed(t["compute"], data["snapshot"]) if "compute" in t else t["value"]
        if value != t["value"]:
            sys.exit("build_stats: tile %d displays %r but the snapshot gives %r" % (n, t["value"], value))
        cells.append(
            '<li class="fx-stat"><span class="fx-stat__num">%02d</span>'
            '<span class="fx-stat__value">%s</span>'
            '<span class="fx-stat__label">%s</span></li>' % (n, html.escape(value), html.escape(t["label"])))
    out = ('<!-- Generated by tools/build_stats.py from data/stats.json; do not edit. -->\n'
           '<ol class="fx-stats" aria-label="Five figures">%s</ol>\n'
           '<p class="fx-stats__source">Career figures from the About page; portfolio figures from the Build by Build '
           'inventory, frozen %s.</p>\n' % ("".join(cells), html.escape(frozen_on())))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print("  wrote %s (5 tiles)" % OUT.relative_to(ROOT).as_posix())


def frozen_on():
    prov = json.loads((ROOT / "data" / "build-by-build.provenance.json").read_text(encoding="utf-8"))
    return prov["frozen_on"]


if __name__ == "__main__":
    main()
